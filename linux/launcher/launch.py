"""Turn a :class:`~launcher.model.Settings` into a running game.

The launcher writes a generated server ``config.toml`` whose only job is to carry the chosen ``[mods] enabled``
list, points ``POWDER_CONFIG`` at it, and runs ``linux/powder-wrap`` with the rest of the environment the
wrapper honors (client mods, overlay). ``powder-wrap`` is invoked as a command prefix: the game command follows it,
by default Ubisoft Connect through umu-run in the detected prefix (game.py), so no Lutris setup is needed.
"""
from __future__ import annotations

import os
import subprocess
from pathlib import Path

from . import game
from .model import Settings


def generated_config_path(s: Settings) -> Path:
    """Beside the repo's config.toml, so its relative paths (data_dir, mods, gamedata) resolve the same."""
    return Path(s.repo) / "config.launcher.toml"


def _esc(v: str) -> str:
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def server_mods(s: Settings) -> list[str]:
    """The server mods to enable: the chosen ones plus the server half (mod.lua) of every chosen client mod."""
    if "*" in s.enabled_mods:
        return ["*"]
    out = list(s.enabled_mods)
    for m in s.client_mods:
        if (Path(s.repo) / "mods" / m / "mod.lua").is_file() and m not in out:
            out.append(m)
    return out


def write_server_config(s: Settings) -> Path:
    """The repo's config.toml (else config.example.toml) with ``[mods] enabled`` replaced by the launcher's
    choice; everything else (ports, data_dir, admins, ...) stays the player's."""
    repo = Path(s.repo)
    base = repo / "config.toml" if (repo / "config.toml").is_file() else repo / "config.example.toml"
    lines = base.read_text(encoding="utf-8").splitlines() if base.is_file() else []
    enabled = "enabled = [" + ", ".join(_esc(m) for m in server_mods(s)) + "]"
    out, section, placed = [], "", False
    for line in lines:
        head = line.strip()
        if head.startswith("[") and not head.startswith("[["):
            section = head.split("#")[0].strip()
            out.append(line)
            if section in ("[mods]", "[plugins]") and not placed:
                out.append(enabled)
                placed = True
            continue
        if section in ("[mods]", "[plugins]") and head.split("=")[0].strip() == "enabled":
            continue
        out.append(line)
    if not placed:
        out += ["", "[mods]", enabled]
    path = generated_config_path(s)
    path.write_text("# Generated by the Powder Linux launcher from " + base.name + "; overwritten on each launch.\n"
                    + "\n".join(out) + "\n", encoding="utf-8")
    return path


def import_lutris(s: Settings, g: "game.LutrisGame | None") -> bool:
    """Take over the Powder settings a player put into Lutris' environment for Ubisoft Connect (once): client mods
    and the overlay. True if anything was taken."""
    if s.imported_lutris or g is None:
        return False
    s.imported_lutris = True
    took = False
    mods = [m for m in g.env.get("POWDER_CLIENT_MODS", "").split(",") if m.strip()]
    if mods and not s.client_mods:
        s.client_mods, took = [m.strip() for m in mods], True
    if g.env.get("POWDER_OVERLAY") == "1" and not s.overlay:
        s.overlay, took = True, True
    return took


def build_env(s: Settings, d: "game.Detected | None" = None) -> dict:
    """The environment for powder-wrap and the game: the launcher's choices plus, unless a game command is set by
    hand, the detected prefix and Proton for umu-run."""
    env: dict[str, str] = {"POWDER_SERVER": s.server_impl}
    env["POWDER_OVERLAY"] = "1" if s.overlay else "0"
    env["POWDER_CLIENT_MODS"] = ",".join(s.client_mods)
    if s.steep_dir:
        env["POWDER_STEEP_DIR"] = s.steep_dir
    env["POWDER_CONFIG"] = str(write_server_config(s))
    if not s.game_command:
        env.update((d or game.detect(s.wine_prefix, s.proton)).env())
    elif s.wine_prefix:
        env["WINEPREFIX"] = s.wine_prefix
    return env


def build_command(s: Settings, d: "game.Detected | None" = None) -> list[str]:
    cmd = s.game_command or (d or game.detect(s.wine_prefix, s.proton)).command()
    return [str(Path(s.repo) / "linux" / "powder-wrap"), *cmd]


def session_log() -> Path:
    """Where powder-wrap writes its session log (the same rule as linux/powder-wrap)."""
    run = os.environ.get("XDG_RUNTIME_DIR")
    if run:
        return Path(run) / "powder-wrap.log"
    return Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "powder" / "powder-wrap.log"


def running_session() -> bool:
    """True while a powder-wrap session runs (its game is closed when it ends)."""
    try:
        out = subprocess.run(["pgrep", "-f", "linux/powder-wrap"], capture_output=True, text=True).stdout
    except OSError:
        return False
    return any(pid.strip() and int(pid) != os.getpid() for pid in out.split())


def last_step() -> str:
    """powder-wrap's latest status line ("powder-wrap: ..."), for the launcher's progress display."""
    try:
        lines = session_log().read_text(errors="replace").splitlines()
    except OSError:
        return ""
    for line in reversed(lines):
        if line.startswith("powder-wrap: ") or line.startswith("world_editor: "):
            return line.split(": ", 1)[1]
        if "product 3279 started" in line:
            return "Steep started"
    return ""


def launch(s: Settings) -> "subprocess.Popen":
    if running_session():
        raise ValueError("A Powder session is already running (close the game and Ubisoft Connect first).")
    d = game.detect(s.wine_prefix, s.proton)
    if not s.game_command and d.problems:
        raise ValueError("Cannot start the game yet:\n" + "\n".join(d.problems))
    return subprocess.Popen(build_command(s, d), env={**os.environ, **build_env(s, d)})
