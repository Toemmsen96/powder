"""Turn a :class:`~launcher.model.Settings` into a running game.

The launcher writes a generated server ``config.toml`` whose only job is to carry the chosen ``[mods] enabled``
list, points ``POWDER_CONFIG`` at it, and runs ``linux/powder-wrap`` with the rest of the environment the
wrapper honors. ``powder-wrap`` is invoked as a command prefix, so the game command follows it verbatim.
"""
from __future__ import annotations

import os
import subprocess
from pathlib import Path

from .model import Settings


def generated_config_path() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "powder" / "linux-launcher-config.toml"


def _esc(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_server_config(s: Settings) -> Path:
    """Write a minimal server config with ``[mods] enabled`` from ``s`` and return its path."""
    enabled = ["*"] if "*" in s.enabled_mods else list(s.enabled_mods)
    path = generated_config_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    body = (
        "# Generated by the Powder Linux launcher; edits are overwritten on the next launch.\n"
        "[mods]\n"
        "enabled = [" + ", ".join(_esc(m) for m in enabled) + "]\n"
    )
    path.write_text(body, encoding="utf-8")
    return path


def build_env(s: Settings) -> dict:
    """The environment overrides powder-wrap honors for ``s`` (overlay/steep-dir only when set)."""
    env: dict[str, str] = {"POWDER_SERVER": s.server_impl}
    if s.overlay:
        env["POWDER_OVERLAY"] = "1"
    if s.steep_dir:
        env["POWDER_STEEP_DIR"] = s.steep_dir
    env["POWDER_CONFIG"] = str(write_server_config(s))
    return env


def build_command(s: Settings) -> list[str]:
    return [str(Path(s.repo) / "linux" / "powder-wrap"), *s.game_command]


def launch(s: Settings) -> "subprocess.Popen":
    if not s.game_command:
        raise ValueError(
            "No game command set. Set the command Lutris uses to start the game "
            "(e.g. the UbisoftConnect.exe launch line) before launching.")
    return subprocess.Popen(build_command(s), env={**os.environ, **build_env(s)})
